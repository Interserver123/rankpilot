import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Embeds supabase/migrations/*.sql into a TS module so the app can apply pending migrations
 * on platforms without a filesystem or shell (e.g. Cloudflare Workers). Runs before every build.
 */
export async function bundledMigrationsSource(root = process.cwd()): Promise<string> {
  const dir = path.join(root, "supabase", "migrations");
  const files = (await readdir(dir)).filter((f) => f.endsWith(".sql")).sort();
  const entries = await Promise.all(files.map(async (f) => ({ name: f, sql: await readFile(path.join(dir, f), "utf8") })));
  return `// Generated by scripts/bundle-migrations.ts — do not edit. Run \`npm run migrations:bundle\`.\nexport const MIGRATIONS: { name: string; sql: string }[] = ${JSON.stringify(entries, null, 2)};\n`;
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  bundledMigrationsSource().then((src) => writeFile(path.join(process.cwd(), "src", "server", "migrations.generated.ts"), src))
    .then(() => console.log("bundled migrations"), (e) => { console.error(e); process.exit(1); });
}
